// Catalog order is stable. Unknown prices are null, never guessed.
// Official sources are retained per product; checked 2026-09-10.
const lens = (
  manufacturerId: string,
  mountId: string,
  sensors: string[],
  id: string,
  name: string,
  focal: number,
  aperture: number,
  url: string,
  price: number | null = null,
  status: Lens["status"] = "current",
): Lens => ({
  manufacturerId,
  mountId,
  sensors,
  id,
  name,
  focal,
  aperture,
  url,
  price,
  status,
  firstParty: true,
  prime: true,
  priceType: price === null ? null : "official",
  priceUpdatedAt: price === null ? null : "2026-09-10",
});
